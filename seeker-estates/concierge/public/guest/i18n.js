const dictionaries = { en, fr, es, de, it };

/** Two-letter UI language from the browser, falling back to English. */
export const locale = (() => {
  const code = String(navigator.language || 'en').slice(0, 2).toLowerCase();
  return dictionaries[code] ? code : 'en';
})();

/** Look up a string and fill {placeholders}. */
export function t(key, vars = {}) {
  const template = dictionaries[locale][key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
